"""Autonomy table (Stage 6.2, M6): a pure reader over frozen match / replay folders ->
Markdown + JSON (contract §6.13). Zero tokens; never writes into a source folder.

    .venv/bin/python tools/autonomy_table.py \\
        --arm "rules off" data/golden/replays/gate-6.1b-2b/*-off \\
        --arm "rules on, empty v0000" data/golden/replays/gate-6.1b-2/*-empty \\
        --arm "rules on, library v5" data/golden/replays/gate-6.1b-2/*-library \\
        --library data/library/rule_library_v0005.json \\
        --title "Stage 6.1b autonomy table" --out data/golden/stats/autonomy_6.1b

`--library` adds the library-rule FP table: hits on benign/holdout_v1.jsonl (TEST data,
scoring only, designer GO 2026-11-18), benign/fixture_v1.jsonl and
benign/fixture_v2_offline.jsonl. Output is deterministic (no timestamps), so the committed
files can be regenerated byte for byte.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from jsonschema import Draft202012Validator

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))
from rules import library as rule_library  # noqa: E402
from stats import autonomy  # noqa: E402
from stats import cost as cost_mod  # noqa: E402
from stats import match_stats as ms  # noqa: E402
from tools import audit_match  # noqa: E402

BENIGN = REPO / "benign"
OFFLINE_SETS = {"holdout_v1": BENIGN / "holdout_v1.jsonl",
                "fixture_v1": BENIGN / "fixture_v1.jsonl",
                "fixture_v2_offline": BENIGN / "fixture_v2_offline.jsonl"}
SCHEMA = Draft202012Validator(json.loads((REPO / "schemas" / "autonomy_table.schema.json")
                                         .read_text(encoding="utf-8")))


def _rel(p: Path) -> str:
    p = Path(p).resolve()
    try:
        return p.relative_to(REPO).as_posix()
    except ValueError:
        return p.as_posix()


def _jl(p: Path) -> list[dict]:
    return ms.read_rounds(p)


def load_folder(d: Path, audits: Path | None = None, golden: Path | None = None
                ) -> autonomy.Folder:
    d = Path(d)
    if not ((d / "match.json").is_file() or (d / "replay.json").is_file()):
        raise ValueError(f"{d} is not a frozen match or replay folder")
    _, rows = audit_match.load_audit(d, audits, golden)
    return autonomy.Folder(name=_rel(d), rounds=_jl(d / "rounds.jsonl"),
                           benign=_jl(d / "benign_results.jsonl"),
                           verdicts=_jl(d / "verdicts.jsonl"),
                           calls=_jl(d / "api_calls.jsonl"), audit_rows=rows,
                           scripted=audit_match.scripted_rounds(d),
                           anomalies=_jl(d / "anomalies.jsonl"))


def build(arms: list[tuple[str, list[Path]]], title: str, library: Path | None = None,
          prices: dict | None = None, offline_sets: dict[str, Path] | None = None) -> dict:
    prices = prices if prices is not None else cost_mod.load_prices()
    doc = {"schema_version": "0.1", "table_version": autonomy.TABLE_VERSION, "title": title,
           "arms": {name: autonomy.arm_table([load_folder(d) for d in dirs], prices)
                    for name, dirs in arms},
           "library_fp": None}
    if library is not None:
        lib = rule_library.load(library)
        sets = {k: _jl(p) for k, p in (offline_sets or OFFLINE_SETS).items()}
        doc["library_fp"] = {"library": _rel(library), "sha256": lib.sha256,
                             "sets": {k: len(v) for k, v in sets.items()},
                             "rules": autonomy.library_fp(lib, sets)}
    errors = [e.message for e in SCHEMA.iter_errors(doc)]
    if errors:
        raise RuntimeError(f"autonomy table is schema-invalid: {errors[:3]}")
    return doc


def write(doc: dict, out: Path) -> tuple[Path, Path]:
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    j, m = out.parent / f"{out.name}.json", out.parent / f"{out.name}.md"
    j.write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    m.write_text(autonomy.markdown(doc), encoding="utf-8")
    return j, m


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--arm", nargs="+", action="append", required=True,
                    metavar=("NAME", "DIR"), help="an arm name followed by its folders")
    ap.add_argument("--library", type=Path, default=None)
    ap.add_argument("--title", default="Autonomy table")
    ap.add_argument("--out", type=Path, default=None,
                    help="output path without suffix (.json and .md); default: print")
    args = ap.parse_args(argv)
    arms = []
    for a in args.arm:
        if len(a) < 2:
            ap.error(f"--arm {a[0]!r} needs at least one folder")
        arms.append((a[0], [Path(x) for x in a[1:]]))
    try:
        doc = build(arms, args.title, args.library)
    except (ValueError, OSError, audit_match.AuditError) as exc:
        print(f"REFUSED: {exc}")
        return 2
    if args.out is None:
        print(autonomy.markdown(doc))
    else:
        for p in write(doc, args.out):
            print(f"wrote {_rel(p)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
